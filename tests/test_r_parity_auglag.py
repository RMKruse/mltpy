def _bounded_config(reference: dict) -> tuple:
    """Decode the bounded fixture's optional bounds into pymlt arguments."""
    from pymlt.optimizer import OptimizerConfig

    lower = reference.get("lower")
    upper = reference.get("upper")
    # R writes JSON NA as null/None → leave as None for pymlt.
    if lower is not None and not np.isfinite(lower):
        lower = None
    if upper is not None and not np.isfinite(upper):
        upper = None
    return OptimizerConfig(solver="auglag", lower=lower, upper=upper)


