def test_auglag_monotonicity_satisfied(reference: dict) -> None:
    """Bernstein coefficients must be non-decreasing at the auglag optimum."""
    from pymlt.basis import BernsteinBasis
    from pymlt.optimizer import OptimizerConfig, optimize

    y = np.array(reference["y"], dtype=np.float64)
    support = tuple(float(v) for v in reference["support"])
    order = int(reference["order"])

    basis = BernsteinBasis(order=order, support=support)
    config = OptimizerConfig(solver="auglag")
    result = optimize(basis, y, config=config)

    theta_b = result.theta[: order + 1]
    assert np.all(np.diff(theta_b) >= -1e-6), (
        f"Monotonicity violated at auglag optimum: theta_b={theta_b}"
    )


def test_reference_starting_point(reference: dict) -> None:
    """Sanity check: stored starting point matches pymlt's _initial_theta."""
    from pymlt.optimizer import _initial_theta

    order = int(reference["order"])
    stored_start = np.array(reference["starting_point"], dtype=np.float64)
    expected_start = _initial_theta(order + 1, None)
    np.testing.assert_allclose(stored_start, expected_start, atol=1e-15)


